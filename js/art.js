  function shade(hex, amt) {
    let h = hex.replace('#', '');
    if (h.length === 3) h = h.split('').map((c) => c + c).join('');
    const n = parseInt(h, 16);
    const clamp = (v) => Math.max(0, Math.min(255, v));
    const r = clamp(((n >> 16) & 255) + amt);
    const g = clamp(((n >> 8) & 255) + amt);
    const b = clamp((n & 255) + amt);
    return '#' + ((r << 16) | (g << 8) | b).toString(16).padStart(6, '0');
  }

  const CELL = 2; // device px per sprite pixel, keeps edges crisp on HiDPI
  const cache = {};

  function get(key, color) {
    const def = SPRITES[key];
    if (!def) return null;
    const base = color || '#999999';
    const cacheKey = key + '|' + base;
    if (cache[cacheKey]) return cache[cacheKey];
    const n = def.rows[0].length;
    const c = document.createElement('canvas');
    c.width = n * CELL;
    c.height = def.rows.length * CELL;
    const g = c.getContext('2d');
    const light = shade(base, 45);
    const dark = shade(base, -65);
    for (let y = 0; y < def.rows.length; y++) {
      for (let x = 0; x < n; x++) {
        let col = null;
        switch (def.rows[y][x]) {
          case '#': col = base; break;
          case 'o': col = light; break;
          case 'x': col = dark; break;
          case 'e': case 'w': col = '#f5f5f5'; break;
          case 'p': col = '#14141c'; break;
          case 'r': col = '#ff4d5e'; break;
          case 'g': col = '#ffd76a'; break;
        }
        if (col) {
          g.fillStyle = col;
          g.fillRect(x * CELL, y * CELL, CELL, CELL);
        }
      }
    }
    cache[cacheKey] = c;
    return c;
  }

  // Draw a sprite centered at (x, y) scaled to `radius`; draws nothing and
  // returns false if `key` has no art (caller falls back to circle+emoji).
  function draw(ctx, key, color, x, y, radius, flip) {
    const s = get(key, color);
    if (!s) return false;
    const size = Math.max(8, Math.round(radius * 2));
    ctx.imageSmoothingEnabled = false;
    if (flip < 0) {
      ctx.save();
      ctx.translate(x, y);
      ctx.scale(-1, 1);
      ctx.drawImage(s, -size / 2, -size / 2, size, size);
      ctx.restore();
    } else {
      ctx.drawImage(s, x - size / 2, y - size / 2, size, size);
    }
    return true;
  }

  return { draw, get };
